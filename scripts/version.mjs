#!/usr/bin/env node
/**
 * The one place that knows how a StageLink version is bumped and where it has
 * to land. `versions.json` is the source of truth; every manifest below is a
 * derived file.
 *
 *   node scripts/version.mjs                       # print
 *   node scripts/version.mjs --check               # are the manifests in sync?
 *   node scripts/version.mjs --sync                # rewrite them from versions.json
 *   node scripts/version.mjs bugs                  # bump both apps
 *   node scripts/version.mjs features mobile       # bump one
 *
 * The desktop and the mobile app version independently, because they ship
 * independently: a phone fix should not move the installer's number.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const SEGMENT = { prod: 0, features: 1, bugs: 2 }
const TARGETS = ['desktop', 'mobile']

const read = (p) => readFileSync(root + p, 'utf8')
/** As `read`, but a file that is not there yet is simply out of date. */
const current = (p) => {
  try {
    return read(p)
  } catch {
    return null
  }
}
/** Render in LF throughout; the write step puts each file's own endings back. */
const lf = (s) => s.replace(/\r\n/g, '\n')
/** A mistyped argument deserves a sentence, not a stack trace. */
const fail = (message) => {
  console.error(message)
  process.exit(1)
}

/** 1.2.3 — bumping a segment resets every segment below it. */
function bump(version, segment) {
  const parts = version.split('.').map(Number)
  if (parts.length !== 3 || parts.some((n) => !Number.isInteger(n) || n < 0))
    fail(`versions.json: "${version}" is not a 1.2.3 version`)
  const at = SEGMENT[segment]
  return parts.map((n, i) => (i < at ? n : i === at ? n + 1 : 0)).join('.')
}

/**
 * Every file a target's version appears in, rendered from its current content.
 * Adding a destination is a line here and nothing else.
 */
function render(target, { version, build }) {
  if (target === 'desktop') {
    const path = 'apps/desktop/package.json'
    return [[path, JSON.stringify({ ...JSON.parse(read(path)), version }, null, 2) + '\n']]
  }
  const line = `version: ${version}+${build}`
  const pubspec = lf(read('apps/mobile/pubspec.yaml')).replace(/^version: .*$/m, line)
  if (!pubspec.includes(line)) throw new Error('apps/mobile/pubspec.yaml: no `version:` line')
  return [
    ['apps/mobile/pubspec.yaml', pubspec],
    [
      'apps/mobile/lib/src/version.dart',
      '// Generated by scripts/version.mjs from versions.json. Do not edit by hand.\n' +
        `const String appVersion = '${version}';\n` +
        `const int appBuild = ${build};\n`,
    ],
  ]
}

const [segment, target = 'all'] = process.argv.slice(2)
const versions = JSON.parse(read('versions.json'))
const show = () => TARGETS.map((t) => `${t} ${versions[t].version}`).join('  ·  ')

if (segment === '--check') {
  const stale = TARGETS.flatMap((t) => render(t, versions[t]))
    .filter(([p, rendered]) => lf(current(p) ?? '') !== rendered)
    .map(([p]) => p)
  if (stale.length) {
    console.error(`Out of sync with versions.json:\n  ${stale.join('\n  ')}\nRun: npm run version:sync`)
    process.exit(1)
  }
  console.log(`In sync — ${show()}`)
  process.exit(0)
}

if (!segment) {
  console.log(show())
  process.exit(0)
}

if (segment !== '--sync') {
  if (!(segment in SEGMENT)) fail(`Expected one of ${Object.keys(SEGMENT).join('/')}, got "${segment}"`)
  const chosen = target === 'all' ? TARGETS : [target]
  if (chosen.some((t) => !TARGETS.includes(t))) fail(`Expected one of ${TARGETS.join('/')}/all, got "${target}"`)

  for (const t of chosen) {
    const was = versions[t].version
    versions[t].version = bump(was, segment)
    // Android requires a strictly increasing versionCode, so the build number
    // only ever goes up — it is not derived from the version.
    if ('build' in versions[t]) versions[t].build += 1
    console.log(`${t}  ${was} -> ${versions[t].version}`)
  }
  writeFileSync(root + 'versions.json', JSON.stringify(versions, null, 2) + '\n')
}

for (const [p, rendered] of TARGETS.flatMap((t) => render(t, versions[t]))) {
  const was = current(p)
  // Keep the file's existing line endings, so a bump is a one-line diff on a
  // CRLF checkout rather than a whole-file rewrite.
  const content = was?.includes('\r\n') ? rendered.replace(/\n/g, '\r\n') : rendered
  if (was === content) continue
  writeFileSync(root + p, content)
  console.log(`  wrote ${p}`)
}
